import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const capabilityArtifactPaths = {
  tools: "packages/mcp/src/tool-definitions/capabilities.ts",
  documentation: "docs/mcp-tools.md"
};
const defaultRoot = dirname(fileURLToPath(new URL(".", import.meta.url)));
const githubTools = new Set(["PlanWorkItems", "ResolveSyncConflict"]);

export function readToolMetadata(root = defaultRoot) {
  return JSON.parse(readFileSync(join(root, "scripts/mcp-tool-metadata.json"), "utf8"));
}

export function toolMetadata(manifest, retainedMetadata = readToolMetadata()) {
  return manifest.capabilities.filter((capability) => capability.tool).map((capability) => {
    const retained = retainedMetadata.find((tool) => tool.name === capability.tool);
    if (!retained?.description) throw new Error(`Missing authored MCP description for ${capability.tool}.`);
    return {
      name: capability.tool,
      description: retained.description,
      permission: retained?.permission ?? (githubTools.has(capability.tool) ? "github" : capability.tool === "CreateAiProposal" ? "proposal" : capability.kind)
    };
  });
}

export function serializeToolDefinitions(manifest, retainedMetadata) {
  return `export const generatedMcpToolDefinitions = ${JSON.stringify(toolMetadata(manifest, retainedMetadata), null, 2)} as const;\n`;
}

export function serializeToolDocumentation(manifest, retainedMetadata) {
  const tools = toolMetadata(manifest, retainedMetadata);
  const descriptions = new Map(tools.map((tool) => [tool.name, tool]));
  const eligible = manifest.capabilities.filter((capability) => capability.tool);
  const humanOnly = manifest.capabilities.filter((capability) => capability.kind === "human-only");
  const coverageRows = manifest.operationCoverage.map((entry) => `| \`${entry.name}\` | ${entry.operations.map((pair) => "`" + pair + "`").join(", ") || "—"} | ${entry.exceptions.join(", ") || "—"} |`);
  const toolRows = eligible.map((capability) => {
    const tool = descriptions.get(capability.tool);
    return `| \`${tool.name}\` | ${tool.permission} | \`${capability.name}\` | ${tool.description} |`;
  });
  const humanRows = humanOnly.map((capability) => `| \`${capability.name}\` | ${capability.route ? `\`${capability.route}\`` : "—"} |`);
  return [
    "# MCP Tools", "",
    "Reproducing statement: Generate the complete MCP tool inventory, human-only boundary and operation-registry coverage from the application capability manifest for Story 4.7. Date: 2026-10-12. Version: 6.", "",
    "Generated by `corepack pnpm generate-capabilities` and during `corepack pnpm build`. `corepack pnpm check-capabilities` detects stale artifacts; runtime parity tests compare this inventory with actual registered tools.", "",
    "Permissions use every touched Project's safety switches: reads and proposals require an Agent mode other than `off`; domain commands retain proposals in Agent mode `propose`; GitHub calls also require the GitHub switch. Runtime-wide reads filter inaccessible Projects. Inputs reuse the contracts' Zod schemas. `ApproveChangeSet` requires access and the default-off human-controlled Agent approval flag, even under protection. `ApplyChangeSet` requires recorded approval and protection off.", "",
    "`ImportSourceDocument` requires non-empty inline `content` over MCP. Its strict input schema excludes and rejects `filePath`; agents cannot read host files through this tool. The human HTTP import route retains content-or-file input.", "",
    "Domain commands accept optional `apply` (omitted means true). Responses expose `changeSet`, `outcome` (`proposed` or `applied`), `changeSetId` and `previewRef.changeSetId`. `apply=false` and Agent mode `propose` retain reviewed proposals without domain application. Stored proposals require approval before `ApplyChangeSet`. Agent push prepares a proposed Dry Run plan; provider mutation requires the separate human HTTP confirmation. Protected Agent push is refused.", "",
    "## Tool inventory", "",
    `The manifest exposes ${tools.length} tools.`, "",
    "| Tool | Permission | Use case | Description |", "| --- | --- | --- | --- |", ...toolRows, "",
    "## Human-only boundary", "",
    "Agents cannot create Projects, change safety switches or connector credentials/configuration, reject ChangeSets, restore or create restore points on demand, import or export Project archives, or perform UI checklist bookkeeping. Read-only safety and public connector metadata remain available through tools.", "",
    "| Use case | HTTP route |", "| --- | --- |", ...humanRows, "",
    "## Operation-registry coverage", "",
    "Every exposed write and effectful read has typed registry members or named lifecycle, administration, remote or bookkeeping exceptions. Mixed sync capabilities retain their local domain members alongside remote/baseline exceptions. View Settings is planned-only outside the exposed-write catalog; AI-template editing remains human-only and new Card dependencies belong to Story 5.1.", "",
    "Capability checks also match every routed domain tool and reject direct repository writes in MCP handlers. Runtime acceptance verifies persisted proposals, executor effects and audit; static coverage alone does not prove execution.", "",
    "| Use case | Registry members | Exceptions |", "| --- | --- | --- |", ...coverageRows, "",
    "## Changelog", "",
    "- 2026-10-28, version 7: Replace Agent access, protection and approval flags with one Agent mode (ADR 0010).",
    "- 2026-10-12, version 6: Route domain commands through ChangeSets, admit protected proposals and classify effectful reads. Human confirmation retains the remote-write boundary.",
    "- 2026-10-12, version 5: Expose conditional Agent approval while retaining human-controlled settings and independent apply protection.",
    "- 2026-10-12, version 4: Classify every exposed write and verify implemented operation pairs.",
    "- 2026-10-08, version 3: Require content-only MCP Source imports while retaining human HTTP file imports.",
    "- 2026-10-08, version 2: Generate the complete inventory and human-only list; record the Epic 4 operation-registry gap.", ""
  ].join("\n");
}
